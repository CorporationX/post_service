-- batch-set-and-expire.lua
-- Атомарно сохраняет несколько ключей и устанавливает одинаковый TTL.
-- ARGV[1]: TTL (время жизни) для ключей в секундах
-- KEYS[1]...: Список ключей для сохранения
-- ARGV[2]...: Список значений для сохранения (по одному на каждый ключ)

local ttl = tonumber(ARGV[1])

-- Проходим по всем ключам, переданным в KEYS
for i = 1, #KEYS do
    -- 1. Сохраняем значение по текущему ключу
    -- ARGV[i+1] соответствует значению для KEYS[i]
    redis.call('SET', KEYS[i], ARGV[i+1])

    -- 2. Устанавливаем срок жизни для этого ключа
    redis.call('EXPIRE', KEYS[i], ttl)
end

-- Возвращаем количество обработанных ключей
return #KEYS